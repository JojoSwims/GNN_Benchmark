"""NOAA NDBC ocean buoy dataset loader.

Reads pre-fetched data from noaa_buoy_data.parquet (generated by
fetch_noaa_data.py) and station coordinates from noaa_buoy_stations.json
(generated by compare_feature_filters.py).

Pipeline:
  1. compare_feature_filters.py  ->  datasets/noaa_buoy_stations.json
  2. fetch_noaa_data.py           ->  datasets/noaa_buoy_data.parquet
  3. This loader reads both files, applies quality filter, builds graph.
"""

from __future__ import annotations

import json
from dataclasses import dataclass, field
from itertools import combinations
from pathlib import Path

import pandas as pd

from gnn_benchmark.core.types import DatasetInfo, WindowConfig
from gnn_benchmark.datasets.base import DatasetLoader
from gnn_benchmark.utils.geo import haversine_distance

# ── Constants ─────────────────────────────────────────────────────────────────

_YEARS = [2022, 2023, 2024, 2025]

# Quality filter: drop buoys with > 50 % missing on the prediction feature
_MAX_MISSING = 0.50
_FILTER_FEATURE = "WSPD"

# WSPD (wind speed) is the prediction target, so it must come first: the model
# wrappers' inverse-transform slices `std[:D_out]` and assumes target columns
# are the leading entries of `feature_columns`.
_FEATURES = ["WSPD", "WTMP", "WVHT", "PRES"]
_UNITS = {"WSPD": "m/s", "WTMP": "degC", "WVHT": "m", "PRES": "hPa"}

# Features where a raw 0 is a sensor artifact, not a real measurement:
# PRES=0 is physically impossible (vacuum), WVHT=0 on an open-ocean buoy is
# essentially impossible, and WSPD=0 is an anemometer stall. Reclassify these
# as NaN so they are excluded from the scoring mask.
_ZERO_AS_MISSING = ("WSPD", "WVHT", "PRES")

# Pre-fetched data files (generated by companion scripts)
_STATIONS_FILE = Path(__file__).parent / "noaa_buoy_stations.json"
_DATA_FILE = Path(__file__).parent / "noaa_buoy_data.parquet"


# ── Loader ────────────────────────────────────────────────────────────────────


@dataclass
class NOAABuoyLoader(DatasetLoader):
    """
    Loader for NOAA NDBC ocean buoy dataset.

    Reads pre-fetched hourly stdmet data from a local parquet file.
    No network calls — run fetch_noaa_data.py first to download the data.

    Features
    --------
    WTMP  sea surface temperature  (degC)
    WSPD  wind speed               (m/s)
    WVHT  significant wave height  (m)
    PRES  sea level pressure       (hPa)

    Graph
    -----
    Fully connected graph: every buoy pair gets an edge weighted by haversine
    distance in km.
    """

    _node_order: list[str] = field(default_factory=list, init=False, repr=False)

    @property
    def info(self) -> DatasetInfo:
        return DatasetInfo(
            name="noaa_buoy",
            url="https://www.ndbc.noaa.gov/data/stations/station_table.txt",
            frequency="1H",
            node_order=list(self._node_order),
            feature_columns=_FEATURES,
            units=_UNITS,
            window_config=WindowConfig(target_columns=["WSPD"]),
            description=(
                "NOAA NDBC ocean buoy network, Western Hemisphere "
                "(lon -180 to -50), 2022-2025 (hourly). Features: wind speed "
                "(WSPD, prediction target), sea surface temperature (WTMP), "
                "significant wave height (WVHT), sea level pressure (PRES). "
                "Quality filter: WSPD <= 50% missing. Missing values are kept "
                "as NaN so the harness scorer masks them out; raw 0s in WSPD/"
                "WVHT/PRES (sensor artifacts) are reclassified as NaN. Edges: "
                "fully connected, weighted by haversine distance (km)."
            ),
        )

    # ── Public entry point ────────────────────────────────────────────────────

    def download_and_convert(self) -> tuple[pd.DataFrame, pd.DataFrame | None]:
        """Load pre-fetched NOAA data from parquet and build IR."""

        # ── Step 1: load station coordinates ─────────────────────────────
        if not _STATIONS_FILE.exists():
            raise FileNotFoundError(
                f"{_STATIONS_FILE} not found. "
                "Run compare_feature_filters.py first."
            )
        stations_map: dict[str, tuple[float, float]] = {
            sid: (v[0], v[1])
            for sid, v in json.loads(_STATIONS_FILE.read_text()).items()
        }

        # ── Step 2: load pre-fetched data ────────────────────────────────
        if not _DATA_FILE.exists():
            raise FileNotFoundError(
                f"{_DATA_FILE} not found. "
                "Run fetch_noaa_data.py first to download buoy data."
            )
        df = pd.read_parquet(_DATA_FILE)
        df["ts"] = pd.to_datetime(df["ts"])
        station_ids = sorted(df["station_id"].unique())
        print(f"Loaded {len(station_ids)} stations from {_DATA_FILE.name}.")

        # ── Step 2b: raw-0 reclassification ─────────────────────────────
        # Reclassify raw 0s (sensor errors, not physical measurements) as NaN
        # so the harness scoring mask excludes them.
        for col in _ZERO_AS_MISSING:
            df[col] = df[col].where(df[col] != 0)

        # ── Step 3: quality filter (WSPD only) ───────────────────────────
        full_index = pd.date_range(
            f"{_YEARS[0]}-01-01",
            f"{_YEARS[-1]}-12-31 23:00",
            freq="1h",
        )
        good: list[str] = []
        filtered: dict[str, pd.DataFrame] = {}
        for sid in station_ids:
            sid_df = df[df["station_id"] == sid].set_index("ts")[_FEATURES]
            sid_df = sid_df.reindex(full_index)
            if sid_df[_FILTER_FEATURE].isna().mean() <= _MAX_MISSING:
                good.append(sid)
                # Keep NaN: the harness scorer masks NaN positions, and all
                # model wrappers normalise with nanmean/nanstd and then call
                # torch.nan_to_num post-scaling (== mean imputation).
                filtered[sid] = sid_df

        good = sorted(good)
        self._node_order = good
        print(f"  {len(good)} buoys passed quality filter "
              f"({_FILTER_FEATURE} <= {_MAX_MISSING*100:.0f}% missing).")

        # ── Step 4: series_df ─────────────────────────────────────────────
        series_df = self._build_series(filtered, good)

        # ── Step 5: edges_df ──────────────────────────────────────────────
        good_stations = pd.DataFrame(
            [(sid, stations_map[sid][0], stations_map[sid][1]) for sid in good],
            columns=["station_id", "lat", "lon"],
        )
        edges_df = self._build_edges(good_stations, good)

        return series_df, edges_df

    # ── Private helpers ───────────────────────────────────────────────────────

    @staticmethod
    def _build_series(
        frames: dict[str, pd.DataFrame],
        station_ids: list[str],
    ) -> pd.DataFrame:
        """Concatenate all stations into long-format series_df."""
        parts = []
        for sid in station_ids:
            chunk = frames[sid][_FEATURES].copy()
            chunk.index.name = "ts"
            chunk = chunk.reset_index()
            chunk["node_id"] = sid
            parts.append(chunk[["ts", "node_id"] + _FEATURES])

        series_df = pd.concat(parts, ignore_index=True)
        series_df = series_df.sort_values(["ts", "node_id"]).reset_index(drop=True)
        return series_df

    @staticmethod
    def _build_edges(
        stations: pd.DataFrame,
        station_ids: list[str],
    ) -> pd.DataFrame:
        """Fully connected symmetric edges weighted by haversine distance (km)."""
        coord_map = (
            stations.set_index("station_id")[["lat", "lon"]].to_dict("index")
        )

        rows: list[tuple[str, str, float]] = []
        for a_id, b_id in combinations(station_ids, 2):
            a = coord_map[a_id]
            b = coord_map[b_id]
            dist_km = round(haversine_distance(a["lat"], a["lon"], b["lat"], b["lon"]) / 1_000.0, 1)
            rows.append((a_id, b_id, dist_km))
            rows.append((b_id, a_id, dist_km))

        return pd.DataFrame(rows, columns=["src", "dst", "cost"])